// Projects the Samar Island boundaries into a compact SVG path set for decorative use (login page).
// Run after `npm run build:geo`: npm run build:art
// Output: src/data/samar-art.js
const fs = require('node:fs')
const path = require('node:path')

const data = path.resolve('public/data')
const target = path.resolve('src/data/samar-art.js')
const read = name => JSON.parse(fs.readFileSync(path.join(data, `${name}.geojson`), 'utf8')).features

const provinces = read('samar-island-provinces')
const localities = read('samar-island-localities')
const allPoints = [...provinces, ...localities].flatMap(feature => {
  const parts = feature.geometry.type === 'Polygon' ? [feature.geometry.coordinates] : feature.geometry.coordinates
  return parts.flatMap(part => part.flatMap(ring => ring))
})
const lons = allPoints.map(([lon]) => lon), lats = allPoints.map(([, lat]) => lat)
const [minLon, maxLon, minLat, maxLat] = [Math.min(...lons), Math.max(...lons), Math.min(...lats), Math.max(...lats)]
// Equirectangular projection with a cosine correction so the island keeps its real proportions.
const k = Math.cos(((minLat + maxLat) / 2) * Math.PI / 180)
const width = 1000
const scale = width / ((maxLon - minLon) * k)
const height = Math.round((maxLat - minLat) * scale)
const project = ([lon, lat]) => [(lon - minLon) * k * scale, (maxLat - lat) * scale].map(value => Math.round(value))

// Whole-unit coordinates; points that land on the same unit as the previous one are dropped.
const toRing = ring => {
  const kept = []
  for (const point of ring) {
    const [x, y] = project(point)
    const last = kept[kept.length - 1]
    if (!last || last[0] !== x || last[1] !== y) kept.push([x, y])
  }
  return kept.map(([x, y], index) => `${index ? 'L' : 'M'}${x} ${y}`).join('') + 'Z'
}
const toPath = geometry => {
  const parts = geometry.type === 'Polygon' ? [geometry.coordinates] : geometry.coordinates
  return parts.map(part => part.map(toRing).join('')).join('')
}

const cityNames = ['Catbalogan City', 'Calbayog City', 'Borongan City', 'Catarman']
const cities = localities
  .filter(feature => cityNames.includes(feature.properties.name))
  .map(feature => ({ name: feature.properties.name, point: project(feature.properties.labelPoint) }))

const art = {
  viewBox: `0 0 ${width} ${height}`,
  provinces: provinces.map(feature => ({ name: feature.properties.name, label: feature.properties.name.replace(' Province', ''), d: toPath(feature.geometry), point: project(feature.properties.labelPoint) })),
  localities: localities.map(feature => ({ name: feature.properties.name, d: toPath(feature.geometry) })),
  cities
}
fs.mkdirSync(path.dirname(target), { recursive: true })
fs.writeFileSync(target, `// Generated by scripts/build-samar-art.cjs. Do not edit by hand.\nexport const samarArt = ${JSON.stringify(art)}\n`)
console.log(`Wrote ${art.localities.length} localities and ${art.provinces.length} provinces (${Math.round(fs.statSync(target).size / 1024)} KB).`)
