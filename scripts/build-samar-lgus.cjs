// Generates src/data/samar-lgus.js: one LGU account per city/municipality on Samar Island, plus a few
// demo consumers for each municipality that has no hand-written seed records.
// Run after `npm run build:geo`: npm run build:lgus
const fs = require('node:fs')
const path = require('node:path')

const data = path.resolve('public/data')
const target = path.resolve('src/data/samar-lgus.js')
const read = name => JSON.parse(fs.readFileSync(path.join(data, `${name}.geojson`), 'utf8')).features

// Municipalities that already have hand-written seed consumers in src/data/seed.js.
const SEEDED = ['Catbalogan City', 'Calbayog City', 'Basey', 'Gandara']
const CONSUMERS_PER_LGU = 3

const localities = read('samar-island-localities').map(f => f.properties)
const barangays = read('samar-island-barangays').map(f => f.properties)
const slug = name => name.toLowerCase().replace(/[()]/g, '').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')

const FIRST = ['Jose', 'Maria', 'Juan', 'Ana', 'Pedro', 'Rosa', 'Carlos', 'Elena', 'Ramon', 'Liza', 'Luis', 'Grace', 'Mario', 'Teresa', 'Dante', 'Nina']
const LAST = ['Santos', 'Reyes', 'Cruz', 'Bautista', 'Garcia', 'Mendoza', 'Villanueva', 'Ramos', 'Aquino', 'Navarro', 'Flores', 'Domingo', 'Lim', 'Soriano', 'Valdez', 'Fernandez']

const lgus = localities.map(loc => ({
  code: loc.code,
  name: loc.name,
  kind: loc.kind,
  province: loc.province,
  email: `lgu.${slug(loc.name)}@drops.ph`
})).sort((a, b) => a.name.localeCompare(b.name))

const consumers = []
let serial = 0
for (const lgu of lgus) {
  if (SEEDED.includes(lgu.name)) continue
  const own = barangays.filter(b => b.localityCode === lgu.code).sort((a, b) => a.code.localeCompare(b.code))
  if (own.length === 0) continue
  for (let i = 0; i < CONSUMERS_PER_LGU; i++) {
    serial++
    const barangay = own[i % own.length]
    const previous = 120 + (serial * 37) % 260
    const current = previous + (serial * 13) % 34
    const name = `${FIRST[serial % FIRST.length]} ${LAST[(serial * 3) % LAST.length]}`
    consumers.push({
      id: `g${serial}`,
      account: `G-2026-${String(serial).padStart(5, '0')}`,
      name,
      province: lgu.province,
      locality: lgu.name,
      barangay: barangay.name,
      address: `${10 + (serial * 7) % 90} ${['Rizal Ave.', 'Mabini St.', 'Quezon Road', 'Barangay Road'][serial % 4]}`,
      meter: `MT-${String(40000 + serial).padStart(6, '0')}`,
      phone: `09${String(180000000 + serial * 971).slice(0, 9)}`,
      email: `${slug(name)}.${serial}@example.com`,
      type: serial % 9 === 0 ? 'Commercial' : 'Residential',
      tier: serial % 9 === 0 ? 'Commercial' : serial % 5 === 0 ? 'Lifeline' : 'Standard',
      previous,
      current,
      status: 'Active',
      limit: 30,
      warning: 24,
      alerts: {lowUsage: true, billReady: true, usageLimit: true}
    })
  }
}

const out = `// Generated by scripts/build-samar-lgus.cjs. Do not edit by hand.
export const samarLgus = ${JSON.stringify(lgus.map(({code, ...lgu}) => lgu))}
export const generatedConsumers = ${JSON.stringify(consumers)}
`
fs.mkdirSync(path.dirname(target), {recursive: true})
fs.writeFileSync(target, out)
console.log(`Wrote ${lgus.length} LGUs and ${consumers.length} demo consumers across ${new Set(consumers.map(c => c.locality)).size} municipalities.`)
